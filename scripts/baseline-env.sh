#!/usr/bin/env bash
# The postgres arm's server: user-space postgres 18.6, extracted from distro debs into a private
# root, initdb'd into a private data directory, started/stopped, and read back. No root, no Docker.
#
# Why this route is the present fact: ticket 82 measured postgres 18.6 (Ubuntu 18.6-3build2) through
# this extraction (`.scratch/80-external-baselines/env.md` records the verified sequence), and it is
# the only postgres on the box. Re-read 2026-10-27T21:37 +08: `docker ps -a` and `docker images`
# were both empty, and `.scratch/90-m5-postgres-env/pull-postgres18.sh` failed with an i/o timeout to
# Docker Hub (rc=1). Docker is therefore not a dependency of this script or of the M5 chain; the M1
# record's extraction survives at `/var/tmp/m1-pg`, which is the default root here.
#
# The config is chosen so a shared-buffer-sized engine fits the same 128 MiB cgroup as flashdb. It
# is minimal, not tuned, and is disclosed verbatim in the run record. `write_config` and `check`
# share the one SETTINGS array below, so the block the server is started with and the block it is
# read back against cannot drift apart.
#
# Usage:
#   scripts/baseline-env.sh setup    # idempotent: download + extract + initdb + write config
#   scripts/baseline-env.sh start    # setup if needed, then start the server
#   scripts/baseline-env.sh stop     # stop the server if it is running
#   scripts/baseline-env.sh check    # read version + every setting back; refuse a mismatch
#   scripts/baseline-env.sh env      # print `export ...` lines for a client in this shell
#   scripts/baseline-env.sh status
#
# Environment: M1_PG_ROOT (default /var/tmp/m1-pg, the M1 extraction), M1_PG_PORT (default 55432),
# M1_PG_DATABASE (default postgres), M1_PG_REQUIRE (optional version `check` refuses to differ, e.g.
# 18.6). An override root needs its own `setup`; `scripts/m1-controlled-run.sh` builds one under its
# run directory and symlinks the extraction into it.
set -euo pipefail

ROOT=${M1_PG_ROOT:-/var/tmp/m1-pg}
PORT=${M1_PG_PORT:-55432}
DATABASE=${M1_PG_DATABASE:-postgres}
REQUIRE=${M1_PG_REQUIRE:-}
DEBS=$ROOT/debs
EXTRACT=$ROOT/root
DATA=$ROOT/data
SOCKET=$ROOT/socket
LOG=$ROOT/pg.log
USER_NAME=${USER:-$(id -un)}
PACKAGES=(postgresql-18 postgresql-client-18 postgresql-common libpq5)
MARKER='# >>> m1-baseline (regenerated by scripts/baseline-env.sh; do not edit)'
# The M1 record's block, value for value. `write_config` renders it and `check` compares the running
# server against the same strings; this array is the one home of the settings.
SETTINGS=(
    shared_buffers=16MB
    max_connections=32
    work_mem=4MB
    maintenance_work_mem=16MB
    fsync=on
    synchronous_commit=on
    wal_level=minimal
    max_wal_senders=0
)

die() { printf 'baseline-env: %s\n' "$*" >&2; exit 1; }

pg_version_dir() {
    local dir
    dir=$(echo "$EXTRACT"/usr/lib/postgresql/*)
    [ -d "$dir/bin" ] || die "no postgres bin directory under $EXTRACT/usr/lib/postgresql"
    echo "$dir"
}

apply_env() {
    PGROOT=$(pg_version_dir)
    export M1_PGROOT=$PGROOT
    export LD_LIBRARY_PATH="$EXTRACT/usr/lib/x86_64-linux-gnu:$PGROOT/lib${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"
    export PATH="$PGROOT/bin:$PATH"
    export M1_PGHOST=$SOCKET M1_PGPORT=$PORT M1_PGUSER=$USER_NAME M1_PGDATABASE=$DATABASE
    export PGHOST=$SOCKET PGPORT=$PORT PGUSER=$USER_NAME PGDATABASE=$DATABASE
}

download() {
    mkdir -p "$DEBS"
    local missing=()
    local pkg
    for pkg in "${PACKAGES[@]}"; do
        # `-L`: a caller may symlink the M1 extraction's `debs/` into its own root (the controlled
        # run does), and find does not descend a command-line symlink without it.
        [ -n "$(find -L "$DEBS" -maxdepth 1 -name "${pkg}_*.deb" -print -quit)" ] || missing+=("$pkg")
    done
    if [ ${#missing[@]} -gt 0 ]; then
        echo "baseline-env: apt-get download ${missing[*]} (configured mirror)" >&2
        ( cd "$DEBS" && apt-get download "${missing[@]}" ) \
            || die "apt-get download failed; the mirror in /etc/apt/sources.list.d must be reachable"
    fi
}

extract() {
    [ -f "$EXTRACT/.extracted" ] && return
    mkdir -p "$EXTRACT"
    local deb
    for deb in "$DEBS"/*.deb; do
        dpkg-deb -x "$deb" "$EXTRACT"
    done
    : > "$EXTRACT/.extracted"
    pg_version_dir >/dev/null
}

initdb_once() {
    [ -f "$DATA/PG_VERSION" ] && return
    mkdir -p "$DATA"
    "$(pg_version_dir)/bin/initdb" -D "$DATA" -U "$USER_NAME" --auth=trust --no-sync >/dev/null
}

write_config() {
    local conf=$DATA/postgresql.conf item
    mkdir -p "$SOCKET"
    # The block is written once and always at the end, so re-running rewrites it instead of
    # appending a second (conflicting) copy.
    sed -i "/^${MARKER//\//\\/}/,\$d" "$conf"
    {
        printf '%s\n' "$MARKER"
        for item in "${SETTINGS[@]}"; do
            printf '%s = %s\n' "${item%%=*}" "${item#*=}"
        done
        printf "unix_socket_directories = '%s'\nport = %s\nlisten_addresses = ''\n" \
            "$SOCKET" "$PORT"
    } >> "$conf"
}

setup() {
    download
    extract
    apply_env
    initdb_once
    write_config
}

running() {
    "$(pg_version_dir)/bin/pg_ctl" -D "$DATA" status >/dev/null 2>&1
}

start() {
    setup
    apply_env
    if running; then
        echo "baseline-env: already running on $SOCKET:$PORT (data $DATA)"
    else
        "$PGROOT/bin/pg_ctl" -D "$DATA" -l "$LOG" -w start >/dev/null
        echo "baseline-env: started $(postgres --version) on $SOCKET:$PORT (data $DATA)"
    fi
    if ! "$PGROOT/bin/psql" -h "$SOCKET" -p "$PORT" -U "$USER_NAME" -d postgres -tAc \
        "SELECT 1 FROM pg_database WHERE datname = '$DATABASE'" | grep -q 1; then
        "$PGROOT/bin/createdb" -h "$SOCKET" -p "$PORT" -U "$USER_NAME" "$DATABASE"
    fi
}

stop() {
    local ctl
    ctl="$(pg_version_dir)/bin/pg_ctl"
    if [ -d "$DATA" ] && "$ctl" -D "$DATA" status >/dev/null 2>&1; then
        "$ctl" -D "$DATA" -m fast -w stop >/dev/null
        echo "baseline-env: stopped"
    fi
}

query() {
    # One scalar, no formatting: the same channel `check` compares and `start` uses.
    "$PGROOT/bin/psql" -X -q -h "$SOCKET" -p "$PORT" -U "$USER_NAME" -d postgres -tAc "$1"
}

check() {
    # Read the version and the M1 record's block back from the RUNNING server and refuse a
    # difference. This is the check the M1 chain calls on every start, so a server that was started
    # with another setting cannot serve a run that claims this one.
    apply_env
    running || die "no server on $SOCKET:$PORT (data $DATA); start it with M1_PG_ROOT=$ROOT $0 start"
    local version server_version data_directory item name want got rc=0
    version=$(query 'select version()')
    server_version=$(query 'show server_version')
    data_directory=$(query 'show data_directory')
    echo "# read at $(date -Is) on $(hostname), user $(id -un) from the running server at $SOCKET:$PORT"
    echo "# method: $PGROOT/bin/psql -h $SOCKET -p $PORT -tAc 'select version()' / 'show <name>'"
    echo "version: $version"
    echo "server_version: $server_version"
    echo "data_directory: $data_directory"
    for item in "${SETTINGS[@]}"; do
        name=${item%%=*}; want=${item#*=}
        got=$(query "show $name" | tr -d ' ')
        if [ "$got" != "$want" ]; then
            printf 'mismatch: %s reported "%s", the M1 record says "%s"\n' "$name" "$got" "$want" >&2
            rc=1
        else
            printf 'setting: %s = %s\n' "$name" "$got"
        fi
    done
    if [ -n "$REQUIRE" ]; then
        case " $server_version " in
            *" $REQUIRE "*) ;;
            *)
                printf 'version mismatch: the server reports "%s", M1_PG_REQUIRE="%s"\n' \
                    "$server_version" "$REQUIRE" >&2
                rc=1
                ;;
        esac
    fi
    [ "$rc" = 0 ] || die "the running server differs from the M1 record's block; refusing to measure under another one"
    echo "checked: version and every setting above match the M1 record's block"
}

status() {
    apply_env
    if running; then
        echo "running: $(postgres --version) data=$DATA socket=$SOCKET port=$PORT user=$USER_NAME"
    else
        echo "stopped: data=$DATA"
    fi
}

case "${1:-}" in
    setup)  setup ;;
    start)  start ;;
    stop)   stop ;;
    check)  check ;;
    env)    apply_env; for name in M1_PGROOT LD_LIBRARY_PATH PATH M1_PGHOST M1_PGPORT \
                                M1_PGUSER M1_PGDATABASE PGHOST PGPORT PGUSER PGDATABASE; do
                printf 'export %s=%q\n' "$name" "${!name}"
            done ;;
    status) status ;;
    *) die "usage: $0 setup|start|stop|check|env|status" ;;
esac
