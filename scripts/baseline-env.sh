#!/usr/bin/env bash
# User-space postgres for the M1 external baselines: download, extract, init, start. No root.
#
# Why this shape: Docker Hub is unreachable on this box and no images are local, so postgres runs
# natively from the distro's own packages, extracted into a private root and pointed at a private
# data directory (`.scratch/80-external-baselines/env.md` records the verified sequence and the
# config below). `apt-get download` resolves through the machine's configured apt mirror, which is
# the aliyun Ubuntu mirror (`/etc/apt/sources.list.d/*.sources`).
#
# The config is chosen so a shared-buffer-sized engine fits the same 128 MiB cgroup as flashdb. It
# is minimal, not tuned, and is disclosed verbatim in the run record.
#
# Usage:
#   scripts/baseline-env.sh setup    # idempotent: download + extract + initdb + write config
#   scripts/baseline-env.sh start    # setup if needed, then start the server
#   scripts/baseline-env.sh stop     # stop the server if it is running
#   scripts/baseline-env.sh env      # print `export ...` lines for a client in this shell
#   scripts/baseline-env.sh status
#
# Environment: M1_PG_ROOT (default /tmp/m1-pg), M1_PG_PORT (default 55432), M1_PG_DATABASE
# (default postgres).
set -euo pipefail

ROOT=${M1_PG_ROOT:-/tmp/m1-pg}
PORT=${M1_PG_PORT:-55432}
DATABASE=${M1_PG_DATABASE:-postgres}
DEBS=$ROOT/debs
EXTRACT=$ROOT/root
DATA=$ROOT/data
SOCKET=$ROOT/socket
LOG=$ROOT/pg.log
USER_NAME=${USER:-$(id -un)}
PACKAGES=(postgresql-18 postgresql-client-18 postgresql-common libpq5)
MARKER='# >>> m1-baseline (regenerated by scripts/baseline-env.sh; do not edit)'

die() { printf 'baseline-env: %s\n' "$*" >&2; exit 1; }

pg_version_dir() {
    local dir
    dir=$(echo "$EXTRACT"/usr/lib/postgresql/*)
    [ -d "$dir/bin" ] || die "no postgres bin directory under $EXTRACT/usr/lib/postgresql"
    echo "$dir"
}

apply_env() {
    PGROOT=$(pg_version_dir)
    export M1_PGROOT=$PGROOT
    export LD_LIBRARY_PATH="$EXTRACT/usr/lib/x86_64-linux-gnu:$PGROOT/lib${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"
    export PATH="$PGROOT/bin:$PATH"
    export M1_PGHOST=$SOCKET M1_PGPORT=$PORT M1_PGUSER=$USER_NAME M1_PGDATABASE=$DATABASE
    export PGHOST=$SOCKET PGPORT=$PORT PGUSER=$USER_NAME PGDATABASE=$DATABASE
}

download() {
    mkdir -p "$DEBS"
    local missing=()
    local pkg
    for pkg in "${PACKAGES[@]}"; do
        [ -n "$(find "$DEBS" -maxdepth 1 -name "${pkg}_*.deb" -print -quit)" ] || missing+=("$pkg")
    done
    if [ ${#missing[@]} -gt 0 ]; then
        echo "baseline-env: apt-get download ${missing[*]} (configured mirror)" >&2
        ( cd "$DEBS" && apt-get download "${missing[@]}" ) \
            || die "apt-get download failed; the mirror in /etc/apt/sources.list.d must be reachable"
    fi
}

extract() {
    [ -f "$EXTRACT/.extracted" ] && return
    mkdir -p "$EXTRACT"
    local deb
    for deb in "$DEBS"/*.deb; do
        dpkg-deb -x "$deb" "$EXTRACT"
    done
    : > "$EXTRACT/.extracted"
    pg_version_dir >/dev/null
}

initdb_once() {
    [ -f "$DATA/PG_VERSION" ] && return
    mkdir -p "$DATA"
    "$(pg_version_dir)/bin/initdb" -D "$DATA" -U "$USER_NAME" --auth=trust --no-sync >/dev/null
}

write_config() {
    local conf=$DATA/postgresql.conf
    mkdir -p "$SOCKET"
    # The block is written once and always at the end, so re-running rewrites it instead of
    # appending a second (conflicting) copy.
    sed -i "/^${MARKER//\//\\/}/,\$d" "$conf"
    cat >> "$conf" <<CONF
$MARKER
shared_buffers = 16MB
max_connections = 32
work_mem = 4MB
maintenance_work_mem = 16MB
fsync = on
synchronous_commit = on
wal_level = minimal
max_wal_senders = 0
unix_socket_directories = '$SOCKET'
port = $PORT
listen_addresses = ''
CONF
}

setup() {
    download
    extract
    apply_env
    initdb_once
    write_config
}

running() {
    "$(pg_version_dir)/bin/pg_ctl" -D "$DATA" status >/dev/null 2>&1
}

start() {
    setup
    apply_env
    if running; then
        echo "baseline-env: already running on $SOCKET:$PORT (data $DATA)"
    else
        "$PGROOT/bin/pg_ctl" -D "$DATA" -l "$LOG" -w start >/dev/null
        echo "baseline-env: started $(postgres --version) on $SOCKET:$PORT (data $DATA)"
    fi
    if ! "$PGROOT/bin/psql" -h "$SOCKET" -p "$PORT" -U "$USER_NAME" -d postgres -tAc \
        "SELECT 1 FROM pg_database WHERE datname = '$DATABASE'" | grep -q 1; then
        "$PGROOT/bin/createdb" -h "$SOCKET" -p "$PORT" -U "$USER_NAME" "$DATABASE"
    fi
}

stop() {
    local ctl
    ctl="$(pg_version_dir)/bin/pg_ctl"
    if [ -d "$DATA" ] && "$ctl" -D "$DATA" status >/dev/null 2>&1; then
        "$ctl" -D "$DATA" -m fast -w stop >/dev/null
        echo "baseline-env: stopped"
    fi
}

status() {
    apply_env
    if running; then
        echo "running: $(postgres --version) data=$DATA socket=$SOCKET port=$PORT user=$USER_NAME"
    else
        echo "stopped: data=$DATA"
    fi
}

case "${1:-}" in
    setup)  setup ;;
    start)  start ;;
    stop)   stop ;;
    env)    apply_env; for name in M1_PGROOT LD_LIBRARY_PATH PATH M1_PGHOST M1_PGPORT \
                                M1_PGUSER M1_PGDATABASE PGHOST PGPORT PGUSER PGDATABASE; do
                printf 'export %s=%q\n' "$name" "${!name}"
            done ;;
    status) status ;;
    *) die "usage: $0 setup|start|stop|env|status" ;;
esac
